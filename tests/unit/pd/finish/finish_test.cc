class TempDir {
 public:
  TempDir()
      : path_(std::filesystem::temp_directory_path() /
              ("eos_finish_test_" + std::to_string(counter_++))) {
    std::filesystem::create_directories(path_);
  }
  ~TempDir() {
    std::error_code ec;
    std::filesystem::remove_all(path_, ec);
  }

  std::string Write(const std::string& name, const std::string& text) const {
    const std::filesystem::path file = path_ / name;
    std::ofstream out(file);
    out << text;
    out.close();
    return file.string();
  }

 private:
  std::filesystem::path path_;
  static inline int counter_ = 0;
};

void LoadDesign(db::OdbDatabase& db, const TempDir& dir,
                const char* lef, const char* def) {
  const std::string lef_path = dir.Write("test.lef", lef);
  ASSERT_TRUE(db.ReadLef(lef_path).ok());
  const std::string def_path = dir.Write("test.def", def);
  ASSERT_TRUE(db.ReadDef(def_path).ok());
}

void FloorplanPlaceRoute(db::OdbDatabase& db, const TempDir& dir) {
  pd::FloorplanOptions foptions;
  pd::FloorplanReport freport;
  ASSERT_TRUE(pd::RunFloorplan(db.RawDatabase(), foptions, &freport).ok());
  ASSERT_GT(freport.row_count, 0);
  pd::PlaceOptions poptions;
  pd::PlaceReport preport;
  ASSERT_TRUE(pd::RunPlace(db.RawDatabase(), poptions, &preport).ok())
      << "place must succeed before route";
  pd::RouteOptions roptions;
  roptions.liberty_path = dir.Write("test.lib", kLiberty);
  pd::RouteReport rreport;
  ASSERT_TRUE(pd::RunRoute(db.RawDatabase(), roptions, &rreport).ok())
      << "route must succeed before finish";
  ASSERT_EQ(rreport.net_routed_count, 3);
}

int CountFillersInDb(odb::dbDatabase* raw) {
  odb::dbBlock* block = raw->getChip()->getBlock();
  int count = 0;
  for (odb::dbInst* inst : block->getInsts()) {
    odb::dbMaster* master = inst->getMaster();
    if (master != nullptr && master->isFiller()) {
      ++count;
      EXPECT_TRUE(inst->isPlaced()) << "filler " << inst->getName()
                                    << " must be placed";
    }
  }
  return count;
}

TEST(Finish, InsertsFillers) {
  TempDir dir;
  db::OdbDatabase db;
  LoadDesign(db, dir, kLef, kDef);
  FloorplanPlaceRoute(db, dir);
  EXPECT_EQ(CountFillersInDb(db.RawDatabase()), 0);
  FinishOptions options;
  FinishReport report;
  const foundation::Status status =
      RunFinish(db.RawDatabase(), options, &report);
  ASSERT_TRUE(status.ok()) << status.message();
  std::cout << "fillers=" << report.filler_count
            << " grid_shapes=" << report.grid_shape_count
            << " metal_fills=" << report.metal_fill_count
            << " pdn=" << report.with_pdn << "\n";
  EXPECT_GT(report.filler_count, 0);
  EXPECT_EQ(report.filler_count, CountFillersInDb(db.RawDatabase()));
  EXPECT_EQ(report.grid_shape_count, 0);
  EXPECT_EQ(report.metal_fill_count, 0);
  EXPECT_FALSE(report.with_pdn);
}

