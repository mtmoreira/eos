// Unit tests: pd/finish (the EOS finish driver: filler insertion,
// basic power grid, metal fill, GDSII stream-out).
//
// Fixture shape mirrors tests/unit/pv/extract/extract_test.cc: one
// site, two routing layers, one two-pin macro in LEF; two placed
// instances, two placed top-level pins, and three two-pin signal
// nets in DEF. Two additions: the BUFX2 macro carries power pins
// (VDD/VSS) and the DEF connects them into POWER/GROUND
// SPECIALNETS, so the -pdn grid has supply nets to build on
// while the routers skip them (TritonRoute refuses POWER nets
// as regular nets, DRT-0305); and the LEF carries
// three filler masters (FILL1/FILL2/FILL4, LEF CLASS CORE SPACER,
// which OpenDB reports through dbMaster::isFiller), so finish has
// filler cells to place. Every finish test floorplans, places, and
// routes (global plus detailed, reusing RunFloorplan/RunPlace/
// RunRoute) before finishing, because finish fails fast on an
// unrouted design by design; those failure modes have their own
// tests below.
//
// The metal-fill rules file is generated by this test, not shipped
// as process data: it is a two-metal JSON file in the upstream
// DensityFill format (one 1.0 um square shape per metal, small
// plausible spacings). It is a test fixture, never a signoff
// rules file: the numbers are documented here as invented for the
// fixture, and no result in this test is presented as a
// process-accurate value.
