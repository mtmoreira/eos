TEST(Finish, RepeatRunIsIdempotent) {
  TempDir dir;
  db::OdbDatabase db;
  LoadDesign(db, dir, kLef, kDef);
  FloorplanPlaceRoute(db, dir);
  FinishOptions options;
  options.with_pdn = true;
  FinishReport first;
  ASSERT_TRUE(RunFinish(db.RawDatabase(), options, &first).ok());
  FinishReport second;
  const foundation::Status status =
      RunFinish(db.RawDatabase(), options, &second);
  ASSERT_TRUE(status.ok()) << status.message();
  // A second run fills no new gaps and rebuilds no grid: the
  // counts come back identical, not accumulated.
  EXPECT_EQ(second.filler_count, first.filler_count);
  EXPECT_EQ(second.grid_shape_count, first.grid_shape_count);
  EXPECT_GT(second.filler_count, 0);
  EXPECT_GT(second.grid_shape_count, 0);
}

