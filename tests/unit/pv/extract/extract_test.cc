// Unit tests: pv/extract (the EOS runner over the imported OpenROAD
// parasitic extractor, OpenRCX).
//
// Fixture shape mirrors tests/unit/pd/route/route_test.cc: one site,
// two routing layers, one two-pin macro in LEF; two placed
// instances, two placed top-level pins, and three two-pin nets in
// DEF. Every extract test floorplans, places, and routes (global
// plus detailed, reusing RunFloorplan/RunPlace/RunRoute) before
// extraction, because extraction fails fast on an unrouted design
// by design; those failure modes have their own tests below.
//
// The extraction model file is generated by this test, not shipped
// as process data: it is a two-metal rules file in the upstream
// OpenRCX format (LayerCount 2, one width entry of 0.06 um per
// metal, four spacing rows per DIST table), with small plausible
// resistance and capacitance numbers chosen so the extractor has
// tables for exactly the fixture's two routing layers. It is a
// test fixture, never a signoff model: the numbers are documented
// here as invented for the fixture, and no result in this test is
// presented as a process-accurate value.
//
// The SPEF the run writes is judged through the existing extracted
// STA path: the test loads it with the session timing service
// (TimingService::Analyze, kExtracted scene with the SPEF) and
// compares worst slack and TNS against the estimated scene on the
// same routed fixture. The two must differ: identical numbers
// would mean the SPEF was not actually applied.
