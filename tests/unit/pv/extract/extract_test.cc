TEST(Extract, GuidesOnlyDesignFailsFast) {
  // A design with guides but no wires is still unrouted for
  // extraction: the global stage alone must not satisfy the routed
  // precondition. Build the guides by routing, then strip the
  // detailed wires the same way the route runner strips a previous
  // run, leaving guides behind.
  TempDir dir;
  db::OdbDatabase db;
  LoadDesign(db, dir, true);
  FloorplanPlaceRoute(db, dir);
  odb::dbBlock* block = db.RawDatabase()->getChip()->getBlock();
  for (odb::dbNet* net : block->getNets()) {
    odb::dbWire* wire = net->getWire();
    if (wire != nullptr) {
      odb::dbWire::destroy(wire);
    }
    EXPECT_GT(static_cast<int>(net->getGuides().size()), 0);
  }
  ExtractOptions options;
  options.spef_path = dir.Write("out.spef", "");
  options.model_path = dir.Write("fixture.rules", RulesText());
  ExtractReport report;
  const foundation::Status status =
      ExtractParasitics(db.RawDatabase(), options, &report);
  ASSERT_FALSE(status.ok());
  EXPECT_EQ(status.code(), ErrorCode::kInvalidState);
  EXPECT_NE(status.message().find("route"), std::string::npos);
}

