// The combinational path n_in -> n_out is constrained by a max
// delay so both STA scenes report a finite worst slack over it.
const char kSdc[] =
    "set_max_delay 1.0 -from [get_ports n_in] -to [get_ports n_out]\n";

// One DIST table body: four spacing rows. Columns are (spacing,
// coupling, fringe, resistance) in the upstream format; the values
// are fixture inventions (see the file banner), chosen so coupling
// falls and fringe rises with spacing, as in the upstream pattern
// tables.
std::string DistRows(const std::string& res)
{
  return "DIST count 4 width 0.06\n"
         "0.06 0.00008 0.00004 " +
         res +
         "\n"
         "0.12 0.00005 0.00005 " +
         res +
         "\n"
         "0.24 0.00002 0.00006 " +
         res +
         "\n"
         "0.48 0 0.00007 " +
         res +
         "\n"
         "END DIST\n";
}

// Resistance DIST rows use the upstream RESOVER row shape
// (dist1, dist2, fringe, resistance). The first column is the
// group key: the imported reader splits RESOVER rows into one
// table per distinct dist1 value and its diagonal-resistance
// lookup unconditionally reads the second group's table, so a
// table with a single dist1 value leaves that slot uninitialized
// and crashes intermittently in getComputeRC_res (the P6 repeat
// crash: first extraction survives on benign heap garbage, the
// second crashes once its tables are allocated over reused heap).
// Upstream pattern tables always carry many dist1 groups, so the
// fixture mirrors that shape: one row per dist1 group, with the
// same dist2 set and the same resistance as before, so the
// extracted values are unchanged. Only the resistance column
// carries fixture meaning here.
std::string ResDistRows(const std::string& res)
{
  return "DIST count 4 width 0.06\n"
         "0 0.06 0 " +
         res +
         "\n"
         "0.06 0.12 0 " +
         res +
         "\n"
         "0.12 0.24 0 " +
         res +
         "\n"
         "0.24 0.48 0 " +
         res +
         "\n"
         "END DIST\n";
}

// Minimal two-metal rules file in the upstream OpenRCX format. The
// section order is the order the upstream parser consumes: for each
// metal, RESOVER then OVER, then (for metal 1 only, the metal below
// the top) UNDER and DIAGUNDER; metal 2 has two over-metals (0 and
// 1) in its RESOVER and OVER sections. DIAGMODEL ON selects the
// one-width DIAGUNDER form.
std::string RulesText()
{
  std::string rules =
      "Extraction Rules for OpenRCX fixture model\n"
      "\n"
      "DIAGMODEL ON\n"
      "\n"
      "LayerCount 2\n"
      "DensityRate 1  0\n"
      "\n"
      "DensityModel 0\n"
      "\n"
      "Metal 1 RESOVER\n"
      "WIDTH Table 1 entries:  0.06\n"
      "\n"
      "Metal 1 RESOVER 0\n" +
      ResDistRows("0.07") +
      "\n"
      "Metal 1 OVER\n"
      "WIDTH Table 1 entries:  0.06\n"
      "\n"
      "Metal 1 OVER 0\n" +
      DistRows("0.07") +
      "\n"
      "Metal 1 UNDER\n"
      "WIDTH Table 1 entries:  0.06\n"
      "\n"
      "Metal 1 UNDER 2\n" +
      DistRows("0.07") +
      "\n"
      "Metal 1 DIAGUNDER\n"
      "WIDTH Table 1 entries:  0.06\n"
      "\n"
      "Metal 1 DIAGUNDER 2\n" +
      DistRows("0.07") +
      "\n"
      "Metal 2 RESOVER\n"
      "WIDTH Table 1 entries:  0.06\n"
      "\n"
      "Metal 2 RESOVER 0\n" +
      ResDistRows("0.05") +
      "\n"
      "Metal 2 RESOVER 1\n" +
      ResDistRows("0.05") +
      "\n"
      "Metal 2 OVER\n"
      "WIDTH Table 1 entries:  0.06\n"
      "\n"
      "Metal 2 OVER 0\n" +
      DistRows("0.05") +
      "\n"
      "Metal 2 OVER 1\n" +
      DistRows("0.05") +
      "\n";
  return rules;
}

class TempDir {
 public:
  TempDir()
      : path_(std::filesystem::temp_directory_path() /
              ("eos_extract_test_" + std::to_string(counter_++))) {
    std::filesystem::create_directories(path_);
  }
  ~TempDir() {
    std::error_code ec;
    std::filesystem::remove_all(path_, ec);
  }

  std::string Write(const std::string& name, const std::string& text) const {
    const std::filesystem::path file = path_ / name;
    std::ofstream out(file);
    out << text;
    out.close();
    return file.string();
  }

 private:
  std::filesystem::path path_;
  static inline int counter_ = 0;
};

void LoadDesign(db::OdbDatabase& db, const TempDir& dir, bool with_def) {
  const std::string lef = dir.Write("test.lef", kLef);
  ASSERT_TRUE(db.ReadLef(lef).ok());
  if (with_def) {
    const std::string def = dir.Write("test.def", kDef);
    ASSERT_TRUE(db.ReadDef(def).ok());
  }
}

void FloorplanPlaceRoute(db::OdbDatabase& db, const TempDir& dir) {
  pd::FloorplanOptions foptions;
  pd::FloorplanReport freport;
  ASSERT_TRUE(pd::RunFloorplan(db.RawDatabase(), foptions, &freport).ok());
  ASSERT_GT(freport.row_count, 0);
  pd::PlaceOptions poptions;
  pd::PlaceReport preport;
  ASSERT_TRUE(pd::RunPlace(db.RawDatabase(), poptions, &preport).ok())
      << "place must succeed before route";
  pd::RouteOptions roptions;
  roptions.liberty_path = dir.Write("test.lib", kLiberty);
  pd::RouteReport rreport;
  ASSERT_TRUE(pd::RunRoute(db.RawDatabase(), roptions, &rreport).ok())
      << "route must succeed before extraction";
  ASSERT_EQ(rreport.net_routed_count, 3);
}

TEST(Extract, ExtractsEveryRoutedNetAndWritesSpef) {
  TempDir dir;
  db::OdbDatabase db;
  LoadDesign(db, dir, true);
  FloorplanPlaceRoute(db, dir);
  const std::string model = dir.Write("fixture.rules", RulesText());
  const std::string spef =
      (std::filesystem::path(dir.Write("out.spef", ""))).string();
  ExtractOptions options;
  options.spef_path = spef;
  options.model_path = model;
  ExtractReport report;
  const foundation::Status status =
      ExtractParasitics(db.RawDatabase(), options, &report);
  ASSERT_TRUE(status.ok()) << status.message();
  // Every routed signal net carries RC segments after extraction.
  std::cout << "nets_extracted=" << report.nets_extracted
            << " rsegs=" << report.rseg_count
            << " cap_nodes=" << report.cap_node_count
            << " cc_segs=" << report.cc_seg_count << "\n";
  EXPECT_EQ(report.nets_extracted, 3);
  EXPECT_GT(report.rseg_count, 0);
  EXPECT_GT(report.cap_node_count, 0);
  EXPECT_EQ(report.spef_path, spef);
  // The SPEF file is non-empty and names all three nets.
  std::ifstream in(spef);
  ASSERT_TRUE(in.good());
  const std::string text((std::istreambuf_iterator<char>(in)),
                         std::istreambuf_iterator<char>());
  EXPECT_NE(text.find("*D_NET"), std::string::npos);
  EXPECT_NE(text.find("n_in"), std::string::npos);
  EXPECT_NE(text.find("n_mid"), std::string::npos);
  EXPECT_NE(text.find("n_out"), std::string::npos);
}

TEST(Extract, ExtractedStaDiffersFromEstimatedSta) {
  TempDir dir;
  db::OdbDatabase db;
  LoadDesign(db, dir, true);
  FloorplanPlaceRoute(db, dir);
  const std::string model = dir.Write("fixture.rules", RulesText());
  const std::string spef = dir.Write("out.spef", "");
  ExtractOptions options;
  options.spef_path = spef;
  options.model_path = model;
  ExtractReport report;
  ASSERT_TRUE(ExtractParasitics(db.RawDatabase(), options, &report).ok());
  const std::string liberty = dir.Write("test.lib", kLiberty);
  const std::string sdc = dir.Write("test.sdc", kSdc);
  analysis::TimingService service;
  db::Scenario estimate;
  estimate.id = 1;
  estimate.name = "estimate";
  estimate.mode = "tt";
  estimate.corner = "tt";
  estimate.parasitics = db::ParasiticsLevel::kEstimate;
  db::Scenario extracted;
  extracted.id = 2;
  extracted.name = "extracted";
  extracted.mode = "tt";
  extracted.corner = "tt";
  extracted.parasitics = db::ParasiticsLevel::kExtracted;
  const auto estimated = service.Analyze(
      db, sdc,
      {analysis::SceneAnalysis{estimate, liberty, ""}});
  ASSERT_TRUE(estimated.ok()) << estimated.status().message();
  const auto extracted_result = service.Analyze(
      db, sdc, {analysis::SceneAnalysis{extracted, liberty, spef}});
  ASSERT_TRUE(extracted_result.ok())
      << extracted_result.status().message();
  const double est_slack =
      estimated.value()[0].metrics.at("worst_slack_ns").value;
  const double ext_slack =
      extracted_result.value()[0].metrics.at("worst_slack_ns").value;
  const double est_tns = estimated.value()[0]
                             .metrics.at("total_negative_slack_ns")
                             .value;
  const double ext_tns = extracted_result.value()[0]
                             .metrics.at("total_negative_slack_ns")
                             .value;
  // The SPEF must actually change the timing: identical numbers
  // would mean the extraction is not wired into STA. Both numbers
  // are printed on every run, and repeated in the failure message
  // when they match.
  std::cout << "estimated worst_slack_ns=" << est_slack << " tns="
            << est_tns << "; extracted worst_slack_ns=" << ext_slack
            << " tns=" << ext_tns << "\n";
  EXPECT_TRUE(est_slack != ext_slack || est_tns != ext_tns)
      << "estimated worst_slack_ns=" << est_slack
      << " tns=" << est_tns << "; extracted worst_slack_ns=" << ext_slack
      << " tns=" << ext_tns;
}

TEST(Extract, RepeatExtractionRewritesCleanly) {
  TempDir dir;
  db::OdbDatabase db;
  LoadDesign(db, dir, true);
  FloorplanPlaceRoute(db, dir);
  const std::string model = dir.Write("fixture.rules", RulesText());
  ExtractOptions options;
  options.model_path = model;
  ExtractReport first;
  options.spef_path = dir.Write("first.spef", "");
  ASSERT_TRUE(ExtractParasitics(db.RawDatabase(), options, &first).ok());
  ExtractReport second;
  options.spef_path = dir.Write("second.spef", "");
  const foundation::Status status =
      ExtractParasitics(db.RawDatabase(), options, &second);
  ASSERT_TRUE(status.ok()) << status.message();
  // Re-extraction replaces the first run's RC data: the counts
  // come back identical, not accumulated.
  EXPECT_EQ(second.nets_extracted, 3);
  EXPECT_EQ(second.rseg_count, first.rseg_count);
  EXPECT_EQ(second.cap_node_count, first.cap_node_count);
  EXPECT_GT(second.rseg_count, 0);
  std::ifstream in(options.spef_path);
  ASSERT_TRUE(in.good());
  const std::string text((std::istreambuf_iterator<char>(in)),
                         std::istreambuf_iterator<char>());
  EXPECT_GT(text.size(), 0u);
  EXPECT_NE(text.find("n_mid"), std::string::npos);
}

